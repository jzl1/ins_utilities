#!/bin/bash
# generate msvcrt import lib from def
cat > build/msvcrt.def <<'DEF'
LIBRARY msvcrt.dll
EXPORTS
malloc
calloc
realloc
free
memcpy
memmove
memset
memcmp
strlen
strcpy
strncpy
strcat
strncat
strcmp
strncmp
_stricmp
_strnicmp
strstr
strchr
strrchr
_strdup
strtok
strtol
strtod
atof
atoi
tolower
toupper
isspace
isdigit
isalpha
isalnum
fopen
fclose
fread
fwrite
fseek
ftell
fflush
fprintf
printf
sprintf
_snprintf
vsprintf
_vsnprintf
sscanf
sin
cos
tan
asin
acos
atan
atan2
sqrt
pow
exp
log
log10
floor
ceil
fabs
fmod
abort
exit
rand
fgets
remove
srand
time
DEF
/usr/bin/llvm-dlltool-18 -m i386 -d build/msvcrt.def -l build/msvcrt.lib 2>/dev/null || /usr/lib/llvm-18/bin/llvm-dlltool -m i386 -d build/msvcrt.def -l build/msvcrt.lib
echo msvcrt.lib generated
